// Regenerates src/eligibility/cog-corse.ts from the site's commune dataset
// (site/src/data/communes.json, itself built from the INSEE COG by generate-communes-dataset.mjs).
//
// À lancer DEPUIS worker/ :   pnpm cog:corse:generate
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type RawCommune = {
  code: string;
  codesHistoriques?: string[];
  communeActuelle?: { code: string };
};

const SOURCE = join(process.cwd(), "../site/src/data/communes.json");
const TARGET = join(process.cwd(), "src/eligibility/cog-corse.ts");

const communes = JSON.parse(readFileSync(SOURCE, "utf8")) as RawCommune[];
const currentCodes = new Set(communes.filter((c) => !c.communeActuelle).map((c) => c.code));
const successors = new Map<string, Set<string>>();

for (const commune of communes) {
  const current = commune.communeActuelle?.code ?? commune.code;

  for (const code of [commune.code, ...(commune.codesHistoriques ?? [])]) {
    if (!code.startsWith("20") || currentCodes.has(code)) continue;
    successors.set(code, (successors.get(code) ?? new Set()).add(current));
  }
}

const ambiguous = [...successors].filter(([, codes]) => codes.size > 1);
if (ambiguous.length > 0) {
  throw new Error(`ambiguous Corsican codes: ${ambiguous.map(([code]) => code).join(", ")}`);
}

const entries = [...successors]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([code, codes]) => `  "${code}": "${[...codes][0]}",`)
  .join("\n");

writeFileSync(
  TARGET,
  `// GENERATED by src/scripts/generate-cog-corse.ts — do not edit by hand.
// Pre-1976 Corsican commune codes (département 20) -> the commune's current code (2A/2B).
export const CORSE_CODE_ACTUEL: Readonly<Record<string, string>> = {
${entries}
};
`,
);

console.log(`[generate-cog-corse] wrote ${successors.size} codes to ${TARGET}`);
